import { build } from 'esbuild'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const root = fileURLToPath(new URL('../', import.meta.url))

/** Build runtime adapters without capturing the extension's workspace helpers. */
export async function buildRuntime() {
  // Hexagonal boundaries: browser, extension host, and MDX server each get
  // artifacts for their runtime; TypeScript remains the only maintained source.
  await Promise.all([
    build({
      absWorkingDir: root,
      entryPoints: {
        noflash: 'scripts/browser/noflash.ts',
        'scripts/hotjar': 'scripts/browser/hotjar.ts'
      },
      outdir: 'public',
      bundle: true,
      format: 'iife',
      platform: 'browser',
      target: 'es2020',
      banner: {
        js: '/* eslint-disable -- Generated by scripts/build-runtime.ts; edit scripts/browser instead. */'
      }
    }),
    build({
      absWorkingDir: root,
      entryPoints: ['tools/mdx-editor/extension.ts'],
      outfile: 'tools/mdx-editor/dist/extension.cjs',
      bundle: true,
      format: 'cjs',
      platform: 'node',
      target: 'node18',
      external: ['vscode']
    }),
    build({
      absWorkingDir: root,
      entryPoints: ['lib/remark-block-ids.ts', 'lib/remark-heading-ids.ts'],
      outdir: '.generated/mdx-plugins',
      outExtension: { '.js': '.mjs' },
      bundle: true,
      format: 'esm',
      platform: 'node',
      target: 'node18'
    }),
    build({
      absWorkingDir: root,
      entryPoints: ['lib/content-preview.ts', 'lib/mdx-format.ts'],
      outdir: '.generated',
      outExtension: { '.js': '.mjs' },
      bundle: true,
      packages: 'external',
      format: 'esm',
      platform: 'node',
      target: 'node18'
    })
  ])
}

if (
  process.argv[1] &&
  pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url
) {
  await buildRuntime()
}
